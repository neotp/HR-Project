CREATE OR REPLACE FUNCTION public.set_attendance_event_type_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_attendance_event_types_updated_at
    ON public.attendance_event_types;
CREATE TRIGGER trg_attendance_event_types_updated_at
BEFORE UPDATE ON public.attendance_event_types
FOR EACH ROW EXECUTE FUNCTION public.set_attendance_event_type_updated_at();

CREATE OR REPLACE FUNCTION public.queue_attendance_recalculation_from_event_type()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.counts_as_work_time IS DISTINCT FROM NEW.counts_as_work_time THEN
        INSERT INTO public.attendance_recalculation_queue(employee_id, work_date, reason)
        SELECT DISTINCT event.employee_id, event.event_date, 'ATTENDANCE_EVENT_TYPE_CHANGED'
        FROM public.attendance_calendar_events event
        WHERE event.event_type = NEW.code
        ON CONFLICT (employee_id, work_date) DO UPDATE
        SET reason = EXCLUDED.reason,
            requested_at = CURRENT_TIMESTAMP,
            attempts = 0,
            last_error = NULL;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_attendance_event_type_recalculation
    ON public.attendance_event_types;
CREATE TRIGGER trg_attendance_event_type_recalculation
AFTER UPDATE OF counts_as_work_time ON public.attendance_event_types
FOR EACH ROW EXECUTE FUNCTION public.queue_attendance_recalculation_from_event_type();
