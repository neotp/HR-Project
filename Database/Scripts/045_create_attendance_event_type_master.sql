CREATE TABLE IF NOT EXISTS public.attendance_event_types
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(30) NOT NULL UNIQUE,
    name_th             VARCHAR(200) NOT NULL,
    name_en             VARCHAR(200),
    counts_as_work_time BOOLEAN NOT NULL DEFAULT FALSE,
    display_order       INTEGER NOT NULL DEFAULT 0,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_attendance_event_type_code CHECK (code <> ''),
    CONSTRAINT ck_attendance_event_type_display_order CHECK (display_order >= 0)
);

